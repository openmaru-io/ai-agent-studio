class TranslateTest(unittest.TestCase):
    def test_물음표는_자리표시자로_바꾸고_따옴표_안은_둔다(self):
        self.assertEqual(db.translate("SELECT * FROM t WHERE a=? AND b='?' AND c=?", True), "SELECT * FROM t WHERE a=%s AND b='?' AND c=%s")

    def test_파라미터가_있으면_퍼센트를_두_번_쓴다(self):
        self.assertEqual(db.translate("SELECT 1 WHERE a LIKE ? AND b LIKE '50%'", True), "SELECT 1 WHERE a LIKE %s AND b LIKE '50%%'")
        self.assertEqual(db.translate("SELECT 'a%b'", False), "SELECT 'a%b'")

    def test_표_정의를_PostgreSQL_로_옮긴다(self):
        out = db.to_pg("CREATE TABLE t (id INTEGER PRIMARY KEY AUTOINCREMENT, ts REAL NOT NULL, note TEXT DEFAULT 'REAL')")
        self.assertIn("BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", out)
        self.assertIn("ts DOUBLE PRECISION", out)

    def test_upsert_는_키를_빼고_나머지를_갱신한다(self):
        sql = db.upsert("t", ("a", "b", "c"), ("a",))
        self.assertEqual(sql, "INSERT INTO t (a,b,c) VALUES (?,?,?) ON CONFLICT (a) DO UPDATE SET b=excluded.b, c=excluded.c")
        self.assertTrue(db.upsert("t", ("a",), ("a",)).endswith("DO NOTHING"))

    def test_문장을_세미콜론으로_나눈다(self):
        self.assertEqual(db.split_statements("CREATE TABLE a (x TEXT DEFAULT ';'); CREATE TABLE b (y INT);"),
                         ["CREATE TABLE a (x TEXT DEFAULT ';')", "CREATE TABLE b (y INT)"])

    def test_행은_이름과_순서로_읽고_dict_가_된다(self):
        r = db.Row(["a", "b"], (1, "x"))
        self.assertEqual((r["a"], r[1], dict(r), tuple(r)), (1, "x", {"a": 1, "b": "x"}, (1, "x")))




