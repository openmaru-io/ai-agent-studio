def tx_depth() -> int:
    """이 스레드가 쥔 PostgreSQL with 의 깊이(0: 밖, 1: 가장 바깥 with 안). SQLite 연결은 세지 않는다."""
    return getattr(_tl, "depth", 0)


def in_write_tx() -> bool:
    """이 스레드가 쓰기 트랜잭션을 열어 둔 채인가(가장 바깥 with 가 BEGIN 을 보냈다). 그 안의 읽기는 되돌려질 수 있다."""
    return getattr(_tl, "depth", 0) > 0 and getattr(_tl, "outer", None) is not None


# 표 캐시(table_cache, 스펙 2026-10-26-002 R10)가 넣는다. write_watch(문장) → 대상 표에 쓰는 문장이면 표 이름.
# write_done(표들) → 그 표의 캐시를 버린다. 쓰는 문장을 볼 때 한 번, 가장 바깥 with 가 끝날 때(커밋 뒤) 한 번 더 부른다(C1)
write_watch: Callable[[str], str | None] | None = None
write_done: Callable[[set], None] | None = None


def _note_write(sql: str) -> None:
    if write_watch is None:
        return
    table = write_watch(sql)
    if table:
        getattr(_tl, "wrote", set()).add(table)
        if write_done is not None:
            write_done({table})


def to_pg(ddl: str) -> str:
    """SQLite 표 정의를 PostgreSQL 로 옮긴다. `REAL` 은 4바이트라 에포크 초가 뭉개지므로 8바이트로 바꾼다."""
    ddl = re.sub(r"INTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT", "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", ddl, flags=re.I)
    ddl = _UNLOGGED.sub(r"CREATE UNLOGGED TABLE IF NOT EXISTS \1", ddl)
    return re.sub(r"\bREAL\b", "DOUBLE PRECISION", ddl)


# 표 이름 뒤의 `/* unlogged */` 는 PostgreSQL 에서 UNLOGGED 표로 만든다(SQLite 는 주석으로 넘긴다). 몇 초 뒤 버리는 값만 둔다 —
# WAL 을 쓰지 않아 커밋 때 디스크(NFS) 동기화를 기다리지 않고, DB 가 비정상 종료되면 비워진다(스펙 2026-10-24-010 D6·D7)
_UNLOGGED = re.compile(r"CREATE\s+TABLE\s+IF\s+NOT\s+EXISTS\s+(\w+)\s*/\*\s*unlogged\s*\*/", re.I)
UNLOGGED_LOCK_TIMEOUT = "2s"     # 예전에 보통 표로 만든 표를 바꿀 때 표 잠금을 기다리는 한도 — 못 얻으면 다음 기동에 다시 한다

# 기동 때 정의 문장마다 LOCK_SCHEMA 로 줄을 서고, CREATE OR REPLACE 는 같은 정의여도 시스템 목록에 써 COMMIT 이 WAL 쓰기를
# 기다렸다. 같은 것이 이미 있으면 건너뛴다. 아래 꼴로 읽어 내지 못하거나 하나라도 다르면 지금처럼 실행한다(스펙 2026-10-28-009 R2)
_DDL_TABLE = re.compile(r"\s*CREATE\s+TABLE\s+IF\s+NOT\s+EXISTS\s+(\w+)", re.I)
_DDL_INDEX = re.compile(r"\s*CREATE\s+(?:UNIQUE\s+)?INDEX\s+IF\s+NOT\s+EXISTS\s+(\w+)", re.I)
_DDL_FUNCTION = re.compile(r"\s*CREATE\s+OR\s+REPLACE\s+FUNCTION\s+(\w+)\s*\(\s*\)\s+RETURNS\s+(\w+)\s+LANGUAGE\s+(\w+)\s+AS\s+\$\$(.*)\$\$\s*$", re.I | re.S)
_DDL_TRIGGER = re.compile(r"\s*CREATE\s+OR\s+REPLACE\s+TRIGGER\s+(\w+)\s+(BEFORE|AFTER)\s+(\w+(?:\s+OR\s+\w+)*)\s+ON\s+(\w+)\s+"
                          r"(?:REFERENCING\s+(NEW|OLD)\s+TABLE\s+AS\s+(\w+)\s+)?FOR\s+EACH\s+(ROW|STATEMENT)\s+"
                          r"EXECUTE\s+(?:FUNCTION|PROCEDURE)\s+(\w+)\s*\(((?:\s*'(?:[^']|'')*'(?!')\s*,?)*)\)\s*$", re.I | re.S)   # (?!') 로 '' 를 한 가지로만 읽는다(CodeQL #1·2)
_TRIGGER_EVENTS = {"INSERT": 4, "DELETE": 8, "UPDATE": 16, "TRUNCATE": 32}   # pg_trigger.tgtype 비트(1: ROW, 2: BEFORE)
# CREATE OR REPLACE FUNCTION 은 문장에 없는 속성을 기본값으로 되돌린다 — 기본값이 아니면 실행해 되돌린다(D4)
_FUNCTION_DEFAULTS = ("v", False, False, None, 100.0, False, False, "u", "f")
_EXISTING_RELATIONS = "SELECT relname FROM pg_class WHERE relnamespace = to_regnamespace(current_schema())"
_EXISTING_FUNCTIONS = ("SELECT p.proname, l.lanname, format_type(p.prorettype, NULL), p.prosrc, p.provolatile, p.proisstrict, p.prosecdef, "
                       "p.proconfig, p.procost, p.proretset, p.proleakproof, p.proparallel, p.prokind FROM pg_proc p "
                       "JOIN pg_language l ON l.oid = p.prolang WHERE p.pronamespace = to_regnamespace(current_schema()) AND p.pronargs = 0")
_EXISTING_TRIGGERS = ("SELECT c.relname, t.tgname, t.tgtype, p.proname, t.tgargs, t.tgnewtable, t.tgoldtable, t.tgenabled FROM pg_trigger t "
                      "JOIN pg_class c ON c.oid = t.tgrelid JOIN pg_proc p ON p.oid = t.tgfoid "
                      "WHERE c.relnamespace = to_regnamespace(current_schema()) AND p.pronamespace = c.relnamespace AND NOT t.tgisinternal")


def _ddl_target(stmt: str) -> tuple[str, Callable[[dict], bool] | None]:
    """정의 문장의 종류와, 이미 있는 것(PgConn._existing)과 같은지 보는 함수. 건너뛸 수 없는 꼴이면 함수 자리가 None."""
    m = _DDL_TABLE.match(stmt)
    if m:
        name = m.group(1).lower()
        return "table", lambda ex: name in ex["rel"]
    m = _DDL_INDEX.match(stmt)
    if m:
        name = m.group(1).lower()
        return "index", lambda ex: name in ex["rel"]
    if re.match(r"\s*CREATE\s+OR\s+REPLACE\s+FUNCTION\b", stmt, re.I):
        m = _DDL_FUNCTION.match(stmt)
        if not m:
            return "function", None
        want = (m.group(3).lower(), m.group(2).lower(), m.group(4)) + _FUNCTION_DEFAULTS
        return "function", lambda ex: ex["fn"].get(m.group(1).lower()) == want
    if re.match(r"\s*CREATE\s+OR\s+REPLACE\s+TRIGGER\b", stmt, re.I):
        m = _DDL_TRIGGER.match(stmt)
        events = [e.upper() for e in re.split(r"\s+OR\s+", m.group(3), flags=re.I)] if m else []
        if not m or any(e not in _TRIGGER_EVENTS for e in events):
            return "trigger", None
        tgtype = sum(_TRIGGER_EVENTS[e] for e in set(events)) | (2 if m.group(2).upper() == "BEFORE" else 0) | (1 if m.group(7).upper() == "ROW" else 0)
        args = b"".join(a.replace("''", "'").encode() + b"\0" for a in re.findall(r"'((?:[^']|'')*)'", m.group(9)))
        ref = (m.group(5) or "").upper()
        table_as = (m.group(6) or "").lower() or None
        want = (tgtype, m.group(8).lower(), args, table_as if ref == "NEW" else None, table_as if ref == "OLD" else None, "O")
        return "trigger", lambda ex: ex["trg"].get((m.group(4).lower(), m.group(1).lower())) == want
    head = re.match(r"\s*CREATE\s+(?:UNIQUE\s+)?(TABLE|INDEX)\b", stmt, re.I)
    return (head.group(1).lower() if head else "other"), None


_COMMENTS = re.compile(r"/\*.*?\*/|--[^\n]*", re.S)
_SELECT = re.compile(r"select\b", re.I)
_LOCKING_SELECT = re.compile(r"\bFOR\s+(NO\s+KEY\s+UPDATE|UPDATE|SHARE|KEY\s+SHARE)\b|\bpg_\w*(advisory|notify)\w*|\b(nextval|setval)\s*\(", re.I)
_QUOTED = re.compile(r"'(?:[^']|'')*'")


def needs_tx(sql: str) -> bool:
    """이 문장 앞에 트랜잭션을 열어야 하나. 읽기만 하는 SELECT 만 거짓 — 첫 쓰기 전까지는 트랜잭션 없이 한 번에 오간다
    (스펙 2026-10-24-009 3-1). SELECT 가 아닌 문장, 여러 문장일 수 있는 것, 잠금·부작용이 있는 SELECT 는 참."""
    text = _QUOTED.sub("''", _COMMENTS.sub(" ", sql)).strip().rstrip(";").strip()
    if ";" in text or not _SELECT.match(text):
        return True
    return bool(_LOCKING_SELECT.search(text))


def translate(sql: str, has_params: bool) -> str:
    """`?` → `%s`(따옴표 밖), 파라미터가 있으면 모든 `%` → `%%`."""
    out, quote = [], None
    for ch in sql:
        if quote:
            out.append("%%" if ch == "%" and has_params else ch)
            if ch == quote:
                quote = None
        elif ch in "'\"":
            quote = ch
            out.append(ch)
        elif ch == "?":
            out.append("%s")
        elif ch == "%" and has_params:
            out.append("%%")
        else:
            out.append(ch)
    return "".join(out)


def split_statements(script: str) -> list[str]:
    parts, buf, quote = [], [], None
    for ch in script:
        if quote:
            buf.append(ch)
            if ch == quote:
                quote = None
        elif ch in "'\"":
            quote = ch
            buf.append(ch)
        elif ch == ";":
            stmt = "".join(buf).strip()
            if stmt:
                parts.append(stmt)
            buf = []
        else:
            buf.append(ch)
    tail = "".join(buf).strip()
    if tail:
        parts.append(tail)
    return parts


def upsert(table: str, columns: tuple[str, ...], keys: tuple[str, ...]) -> str:
    """`INSERT OR REPLACE` 를 두 데이터베이스에서 같게 동작하는 `ON CONFLICT DO UPDATE` 로 쓴다. 열을 모두 적는다."""
    rest = [c for c in columns if c not in keys]
    marks = ",".join("?" * len(columns))
    head = f"INSERT INTO {table} ({','.join(columns)}) VALUES ({marks}) ON CONFLICT ({','.join(keys)}) "
    if not rest:
        return head + "DO NOTHING"
    return head + "DO UPDATE SET " + ", ".join(f"{c}=excluded.{c}" for c in rest)


def upsert_many(table: str, columns: tuple[str, ...], keys: tuple[str, ...], count: int) -> str:
    """여러 행을 한 문장으로 넣는 upsert. count <= 0 이면 빈 문자열."""
    if count <= 0:
        return ""
    rest = [c for c in columns if c not in keys]
    row_marks = f"({','.join('?' * len(columns))})"
    all_marks = ", ".join([row_marks] * count)
    head = f"INSERT INTO {table} ({','.join(columns)}) VALUES {all_marks} ON CONFLICT ({','.join(keys)}) "
    if not rest:
        return head + "DO NOTHING"
    return head + "DO UPDATE SET " + ", ".join(f"{c}=excluded.{c}" for c in rest)


def columns(conn, table: str) -> set[str]:
    """표의 열 이름. `PRAGMA table_info` 와 `information_schema` 의 차이를 가린다."""
    if is_pg(conn):
        rows = conn.execute("SELECT column_name FROM information_schema.columns WHERE table_schema=current_schema() AND table_name=?", (table,))
        return {r[0] for r in rows}
    return {r[1] for r in conn.execute(f"PRAGMA table_info({table})")}


def add_column(conn, table: str, ddl: str) -> None:
    """옛 DB 에 열을 더한다. 서버 두 대(PostgreSQL)나 스레드 여럿(SQLite)이 동시에 더해도 두 번째가 실패하지 않는다."""
    if is_pg(conn):
        # 열이 있어도 ALTER 는 표 전체 잠금(ACCESS EXCLUSIVE)을 잡고 WAL 쓰기 COMMIT 을 기다린다 — 있으면 보내지 않는다(스펙 2026-10-28-009 R1)
        if ddl.split()[0].lower() in columns(conn, table):
            return
        conn.execute(f"ALTER TABLE {table} ADD COLUMN IF NOT EXISTS {ddl}")
        return
    try:
        conn.execute(f"ALTER TABLE {table} ADD COLUMN {ddl}")
    except sqlite3.OperationalError as exc:
        if "duplicate column" not in str(exc):
            raise


def table_names(conn) -> set[str]:
    if is_pg(conn):
        rows = conn.execute("SELECT table_name FROM information_schema.tables WHERE table_schema=current_schema()")
        return {r[0] for r in rows}
    return {r[0] for r in conn.execute("SELECT name FROM sqlite_master WHERE type='table'")}


def lock_events(conn) -> None:
    """PostgreSQL 에서 office_events 삽입을 한 줄로 세운다. id 순서와 커밋 순서가 같아야 `id > after` 로 읽는 쪽이 이벤트를 놓치지 않는다."""
    if is_pg(conn):
        conn.execute("SELECT pg_advisory_xact_lock(?)", (LOCK_EVENTS,))


class Row(tuple):
    """sqlite3.Row 처럼 이름·순서로 읽는다. `dict(row)` 도 된다."""

    def __new__(cls, cols, values):
        self = super().__new__(cls, values)
        self._cols = list(cols)
        return self

    def keys(self):
        return list(self._cols)

    def __getitem__(self, key):
        if isinstance(key, str):
            return tuple.__getitem__(self, self._cols.index(key))
        return tuple.__getitem__(self, key)


def _row_factory(cursor):
    cols = [c.name for c in cursor.description or []]
    return lambda values: Row(cols, values)


class _Backend:
    """설정 하나(호스트·DB·스키마)에 풀 하나. 표 만들기 기록도 여기에 둔다(스키마마다 따로 만든다)."""

    def __init__(self, cfg: dict):
        self.cfg = cfg
        self.pool = None
        self.ddl_done: set[str] = set()
        self.script_done: set[tuple[str, str]] = set()    # (스키마, 표 정의 묶음) — executescript 가 다 처리한 묶음
        self.existing: dict[str, dict] = {}                 # 스키마 → 이미 있는 관계·함수·트리거(PgConn._existing)
        self.ddl_count: Counter = Counter()                 # ("skip"|"run", 종류) → 수. ddl_report_line 이 비운다(R4)
        self.lock = threading.Lock()

    def conninfo(self, connect_timeout: int | None = None) -> str:
        from psycopg.conninfo import make_conninfo
        c = self.cfg
        extra = {"connect_timeout": connect_timeout} if connect_timeout else {}
        # 끊긴 연결을 약 60초 안에 알아챈다(keepalive 30초 뒤 10초마다 3번, 보내기는 30초). 없으면 OS 기본값(2시간·약 15분)이라
        # DB 노드가 갑자기 없어질 때 쿼리가 멈추고 풀이 바닥났다(스펙 2026-10-24-002 R6·R7·D3)
        options = (f"-c search_path={c['schema']} -c statement_timeout={c.get('statement_timeout', '30s')} "
                   f"-c lock_timeout={c.get('lock_timeout', '10s')} -c idle_in_transaction_session_timeout={c.get('idle_tx_timeout', '60s')}")
        return make_conninfo("", host=c["host"], port=c["port"], dbname=c["dbname"], user=c["user"],
                             password=c["password"] or None, sslmode=c["sslmode"], options=options,
                             keepalives=1, keepalives_idle=30, keepalives_interval=10, keepalives_count=3, tcp_user_timeout=30000, **extra)

    def open(self):
        with self.lock:
            if self.pool is not None:
                return self.pool
            from psycopg_pool import ConnectionPool, PoolTimeout
            c = self.cfg
            # 풀 연결은 늘 autocommit 이다. 트랜잭션은 첫 쓰기·잠금 문장·안쪽 with 에서 PgConn._begin 이 연다 — 읽기만 하는
            # with 가 BEGIN·COMMIT 으로 두 번 더 오가지 않게(스펙 2026-10-24-009 3-1)
            pool = ConnectionPool(self.conninfo(5), min_size=c["pool_min"], max_size=c["pool_max"], timeout=c["pool_timeout"],
                                  kwargs={"row_factory": _row_factory, "autocommit": True}, open=False, name="aas")
            pool.open()
            try:
                pool.wait(timeout=c["connect_wait"])          # 풀이 스스로 백오프로 다시 붙는다
            except PoolTimeout as exc:
                pool.close()
                raise DbUnavailable(f"PostgreSQL {c['host']}:{c['port']} 에 {c['connect_wait']:.0f}초 안에 붙지 못했다") from exc  # i18n-ignore: 서버 로그에 남는 운영자용 오류
            self.pool = pool
            return pool


def _tl_schema() -> str:
    """이 호출이 쓸 스키마. `AAS_DB_SCHEMA=auto` 는 시험용으로 AAS_DATA_DIR 마다 스키마를 따로 쓴다(시험끼리 데이터가 섞이지 않는다)."""
    name = config.db_settings()["schema"]
    if name == "auto":
        import hashlib
        return "t_" + hashlib.sha1(str(config.data_dir_default()).encode()).hexdigest()[:12]
    return name


_backends: dict[tuple, _Backend] = {}
_backends_lock = threading.Lock()
_tl = threading.local()          # 이 스레드가 쥔 연결: conn, depth, outer(바깥 트랜잭션, 열었으면), txs(세이브포인트)


def _backend() -> _Backend:
    cfg = config.db_settings()
    if cfg["schema"] == "auto":
        cfg = {**cfg, "schema": "public"}          # auto 는 연결을 빌릴 때 search_path 를 정한다
    key = tuple(sorted(cfg.items()))
    with _backends_lock:
        be = _backends.get(key)
        if be is None:
            be = _backends[key] = _Backend(cfg)
        return be


def reset() -> None:
    """시험이 풀과 확인 연결을 닫고 처음으로 돌아가는 데 쓴다."""
    with _backends_lock:
        for be in _backends.values():
            if be.pool is not None:
                be.pool.close()
        _backends.clear()
    with _ping_lock:
        _ping_close()
    _pool_ok["at"] = float("-inf")                 # 풀을 새로 시작하면 「최근 성공」도 잊는다(R12)


atexit.register(reset)             # 종료 때 풀의 일꾼 스레드를 먼저 닫는다


PING_REUSE = 60.0                # 확인 연결을 다시 쓰는 시간(초). 지나면 새로 맺어 「새 연결을 맺을 수 없는」 상태도 알아챈다
_ping: dict = {"conn": None, "at": 0.0}
_ping_lock = threading.Lock()
_ping_clock = time.monotonic
RECENT_OK = 10.0                 # 이 프로세스의 DB 문장이 이만큼 안에 성공했으면 /readyz 는 확인 문장을 보내지 않는다(스펙 2026-10-26-002 R12)
_pool_ok: dict = {"at": float("-inf")}


def _mark_ok() -> None:
    _pool_ok["at"] = _ping_clock()


def _ping_close() -> None:
    conn, _ping["conn"] = _ping["conn"], None
    if conn is not None:
        try:
            conn.close()
        except Exception:
            pass


def _ping_once(timeout: float, reuse: bool) -> bool:
    import psycopg
    if reuse and _ping["conn"] is not None and not _ping["conn"].closed and _ping_clock() - _ping["at"] < PING_REUSE:
        try:
            _ping["conn"].execute("SELECT 1")
            return True
        except Exception:
            _ping_close()                   # 끊겼다 — 아래에서 한 번 새로 맺어 다시 본다
    conn = psycopg.connect(_backend().conninfo(max(1, int(timeout))), autocommit=True)
    try:
        conn.execute("SELECT 1")
    except Exception:
        conn.close()
        raise
    if not reuse:
        conn.close()
        return True
    _ping_close()
    _ping["conn"], _ping["at"] = conn, _ping_clock()
    return True


def ping(timeout: float = 2.0) -> bool:
    """`/readyz` 가 쓴다. 풀이 아니라 풀 밖 확인 연결로 `SELECT 1` 을 실행해 풀이 가득 차도 점검이 막히지 않는다.
    확인 연결은 60초 동안 다시 쓴다 — 확인마다 새 세션(약 22ms)을 맺어 분당 13개쯤 생겼다(스펙 2026-10-24-010 R3·D4).
    autocommit 이어야 한다 — 아니면 `SELECT 1` 뒤 트랜잭션 중 쉼(60초 한도)으로 끊긴다. 다른 확인이 잠금을 쥐고 있으면
    (반쯤 끊긴 소켓에서 멈춘 채 버려진 확인) 기다리지 않고 새 연결로 확인한다."""
    if backend() != "postgres":
        return True
    if _ping_clock() - _pool_ok["at"] < RECENT_OK:   # 방금 다른 문장이 성공했다 — 프로브마다 SELECT 1 을 보냈다(R12)
        return True
    try:
        if not _ping_lock.acquire(blocking=False):
            return _ping_once(timeout, reuse=False)
        try:
            return _ping_once(timeout, reuse=True)
        finally:
            _ping_lock.release()
    except Exception:
        return False


def pool_stats() -> dict:
    """풀 통계(마지막 호출 뒤 쌓인 값, 부를 때마다 0으로 돌아간다). 서버마다 한 곳(`_office_loop`)에서만 부른다. 풀이 없으면 빈 값."""
    if backend() != "postgres":
        return {}
    pool = _backend().pool
    return dict(pool.pop_stats()) if pool is not None else {}


def pool_report_line(st: dict) -> str | None:
    """5분 풀 기록 한 줄. 기다림·실패·끊김이 없으면 None(로그를 늘리지 않는다, 스펙 2026-10-24-010 Q4).
    `pop_stats` 는 0 인 키를 빼고, 「가장 오래 기다림」은 없다(합계만). 기다림에는 풀이 자라는 동안 기다린 것도 들어간다."""
    g = lambda k: int(st.get(k, 0))  # noqa: E731
    queued, errors = g("requests_queued"), g("requests_errors")
    lost, bad, conn_err = g("connections_lost"), g("returns_bad"), g("connections_errors")
    if not (queued or errors or lost or bad or conn_err):
        return None
    wait_ms = g("requests_wait_ms")
    avg = wait_ms // queued if queued else 0
    return (f"DB 풀(5분): 기다림 {queued}건 합계 {wait_ms}ms 평균 {avg}ms, 연결 {g('pool_size')}/최대 {g('pool_max')}, "  # i18n-ignore: 로그
            f"쉬는 연결 {g('pool_available')}, 실패 {errors}, 끊김 {lost}, 나쁜 반납 {bad}, 연결 실패 {conn_err}")


_DDL_KINDS = (("table", "표"), ("index", "색인"), ("function", "함수"), ("trigger", "트리거"), ("other", "그 밖"))  # i18n-ignore: 로그


def ddl_report_line() -> str | None:
    """정의 문장의 종류별 건너뜀·실행 수(마지막 호출 뒤 쌓인 값, 부르면 비운다). 없으면 None. 5분 풀 기록과 함께 남긴다 —
    다시 기동한 서버의 첫 줄에서 「실행」이 0 에 가까우면 건너뛰기가 동작한다(스펙 2026-10-28-009 R4)."""
    if backend() != "postgres":
        return None
    be = _backend()
    counts, be.ddl_count = be.ddl_count, Counter()
    part = lambda verb: "·".join(f"{label} {counts[verb, k]}" for k, label in _DDL_KINDS if counts[verb, k])  # noqa: E731
    skipped, ran = part("skip"), part("run")
    if not (skipped or ran):
        return None
    return f"표 정의: 건너뜀 {skipped or 0}, 실행 {ran or 0}"  # i18n-ignore: 로그


def check_pool() -> None:
    """풀에 쉬던 연결을 한 번씩 점검해 끊긴 것을 버린다. 알림 연결이 다시 붙을 때(PostgreSQL 다시 시작 뒤) 부른다 —
    풀은 빌려줄 때 확인하지 않아 끊긴 연결이 첫 요청에서 오류를 냈다(스펙 2026-10-24-010 D8)."""
    if backend() != "postgres":
        return
    pool = _backend().pool
    if pool is not None:
        pool.check()


class PgCursor:
    def __init__(self, cur=None, rows=None, rowcount=-1):
        self._cur, self._rows, self.rowcount = cur, rows, (cur.rowcount if cur is not None else rowcount)

    def fetchone(self):
        if self._rows is not None:
            return self._rows.pop(0) if self._rows else None
        return self._cur.fetchone() if self._cur.description else None

    def fetchall(self):
        if self._rows is not None:
            rows, self._rows = self._rows, []
            return rows
        return self._cur.fetchall() if self._cur.description else []

    def __iter__(self):
        return iter(self.fetchall())


def _transaction(conn):
    """psycopg.Transaction 을 직접 만든다. conn.transaction() 은 generator 로 만든 context manager 라, 쓰는 중에 서버가 끝나
    thread-local 이 지워질 때 generator 가 닫히며 __exit__ 가 연결 잠금을 기다려 종료가 멈췄다(test_ws SIGTERM, 2026-10-24)."""
    import psycopg
    return psycopg.Transaction(conn)


class PgConn:
    """sqlite3 연결처럼 보이는 PostgreSQL 연결. 풀에서 빌리는 시점은 가장 바깥 `with` 의 진입(또는 `with` 밖의 첫 문장)이다."""

    def __init__(self, be: _Backend):
        self._be = be

    # ---- with: 같은 스레드의 중첩은 연결을 재사용한다 ----
    # 가장 바깥 with 는 트랜잭션 없이(autocommit) 시작한다. 읽기만 하면 BEGIN·COMMIT 을 보내지 않는다. 쓰기·잠금 문장이나
    # 안쪽 with 가 오면 _begin 이 바깥 트랜잭션을 연다. 바깥을 명시하지 않으면 IDLE 연결의 안쪽 transaction() 을 psycopg 가
    # 바깥으로 보고 안쪽 블록을 나갈 때 따로 커밋한다(스펙 2026-10-24-009 외부 검토 C1). 격리 수준이 READ COMMITTED 라
    # 트랜잭션 안의 SELECT 도 문장마다 새 값을 보므로, 첫 쓰기 전 읽기를 트랜잭션 밖에서 해도 결과가 같다
    def __enter__(self):
        depth = getattr(_tl, "depth", 0)
        if depth == 0:
            _tl.conn = self._acquire()
            _tl.outer = None
            _tl.txs = []
            _tl.wrote = set()
            _tl.ddl_pending = []                 # 이 트랜잭션 안에서 실행한 정의 문장 (깊이, 열쇠) — 커밋되면 ddl_done 으로
        else:
            self._begin()
            tx = _transaction(_tl.conn)          # 안쪽 with 는 세이브포인트
            tx.__enter__()
            _tl.txs.append(tx)
        _tl.depth = depth + 1
        return self

    def __exit__(self, exc_type, exc, tb):
        _tl.depth -= 1
        if _tl.depth > 0:
            _tl.txs.pop().__exit__(exc_type, exc, tb)
            if exc_type is not None:             # 이 세이브포인트가 롤백됐다 — 그 안의 정의 문장은 없던 일이다
                _tl.ddl_pending = [p for p in _tl.ddl_pending if p[0] <= _tl.depth]
            return False
        conn, outer, _tl.conn, _tl.outer = _tl.conn, _tl.outer, None, None
        wrote, _tl.wrote = getattr(_tl, "wrote", set()), set()
        pending, _tl.ddl_pending = getattr(_tl, "ddl_pending", []), []
        try:
            if outer is not None:                # 열지 않았으면 COMMIT·ROLLBACK 을 보내지 않는다
                outer.__exit__(exc_type, exc, tb)
            if exc_type is None:                 # 커밋됐다 — 트랜잭션 안에서 실행한 정의 문장도 이제 다시 실행하지 않는다
                self._be.ddl_done.update(key for _, key in pending)
        finally:
            self._be.pool.putconn(conn)
            if wrote and write_done is not None:   # 커밋(또는 롤백) 뒤 — 읽는 사이 커밋 전 값을 저장한 스레드도 다음에 다시 읽는다
                write_done(wrote)
        return False

    @staticmethod
    def _begin() -> None:
        """이 with 의 바깥 트랜잭션을 연다(이미 열었으면 그대로)."""
        if _tl.outer is None:
            _tl.outer = _transaction(_tl.conn)
            _tl.outer.__enter__()

    def _acquire(self):
        from psycopg_pool import PoolTimeout
        pool = self._be.open()
        try:
            conn = pool.getconn(timeout=self._be.cfg["pool_timeout"])
        except PoolTimeout as exc:
            raise DbUnavailable("PostgreSQL 연결 풀에서 연결을 얻지 못했다(대기 제한 초과)") from exc  # i18n-ignore: 서버 로그에 남는 운영자용 오류
        if config.db_settings()["schema"] == "auto":
            schema = _tl_schema()
            with conn.transaction():
                conn.execute("SET LOCAL lock_timeout = 0")                          # 스키마 잠금은 DDL 이 끝날 때까지 기다린다(외부 검토 2)
                conn.execute("SELECT pg_advisory_xact_lock(%s)", (LOCK_SCHEMA,))     # 여러 스레드가 같은 스키마를 동시에 만들지 않게
                conn.execute(f'CREATE SCHEMA IF NOT EXISTS "{schema}"')
                conn.execute(f'SET search_path TO "{schema}"')
        return conn

    # ---- 문장 실행 ----
    def execute(self, sql: str, params=None):
        head = sql.lstrip()[:12].upper()
        if head.startswith("CREATE"):
            return self._ddl(sql)
        text = translate(sql, bool(params))
        if getattr(_tl, "depth", 0) > 0:
            if needs_tx(sql):
                self._begin()
            cur = PgCursor(_tl.conn.execute(text, params or None))
            _mark_ok()
            _note_write(sql)
            return cur
        with self:                                   # with 밖: 한 문장을 autocommit 으로(한 문장이라 그 자체로 원자적이다)
            cur = _tl.conn.execute(text, params or None)
            rows = cur.fetchall() if cur.description else []
            _mark_ok()
            _note_write(sql)
            return PgCursor(rows=rows, rowcount=cur.rowcount)

    def executescript(self, script: str):
        # 모듈마다 연결할 때마다 같은 표 정의 묶음을 부른다. 묶음째 한 번만 처리한다 — 연결마다 글자 단위로 다시 쪼개고
        # 문장마다 설정을 읽어 요청 CPU 의 약 40% 를 썼다(스펙 2026-10-24-006 §6)
        key = (_tl_schema(), script)
        if key in self._be.script_done:
            return
        for stmt in split_statements(script):
            self._ddl(stmt)
        self._be.script_done.add(key)

    def _ddl(self, stmt: str):
        be = self._be
        schema = _tl_schema()
        key = (schema, stmt)
        if key in be.ddl_done:
            return PgCursor(rows=[])
        kind, same = _ddl_target(stmt)
        # 부른 쪽 트랜잭션 안의 문장은 그 롤백에 함께 사라진다 — 목록을 보지 않고, 커밋된 뒤에만 「실행함」으로 기억한다(스펙 2026-10-28-009 D6)
        outer = tx_depth() > 0
        if not outer and same is not None and same(self._existing(schema)):
            be.ddl_count["skip", kind] += 1        # 같은 것이 이미 있다 — 잠금·트랜잭션을 열지 않는다(R2)
        else:
            with self:
                self._begin()
                _tl.conn.execute("SET LOCAL statement_timeout = 0")   # 큰 테이블의 인덱스 만들기는 30초를 넘을 수 있다(R6). 이 트랜잭션만
                _tl.conn.execute("SET LOCAL lock_timeout = 0")        # 다른 복제본의 DDL 이 끝날 때까지 스키마·표 잠금을 기다린다(외부 검토 2)
                _tl.conn.execute("SELECT pg_advisory_xact_lock(%s)", (LOCK_SCHEMA,))
                _tl.conn.execute(to_pg(stmt))
            be.ddl_count["run", kind] += 1
        m = _UNLOGGED.search(stmt)
        if m:
            self._make_unlogged(m.group(1))
        if outer:                                  # 부른 쪽 트랜잭션이 커밋돼야 기억한다(__exit__). 롤백되면 다음에 다시 만든다
            _tl.ddl_pending.append((tx_depth(), key))
        else:
            be.ddl_done.add(key)
        return PgCursor(rows=[])

    def _existing(self, schema: str) -> dict:
        """이 스키마에 이미 있는 관계·함수·트리거. 스키마마다 처음 한 번 읽어 기억하고, 정의 문장을 실행한 뒤에도 고치지 않는다 —
        목록에 없으면 지금처럼 실행할 뿐이다(D6). 읽지 못하면 빈 목록(모두 실행)."""
        found = self._be.existing.get(schema)
        if found is None:
            try:
                with self:
                    found = {"rel": {r[0] for r in _tl.conn.execute(_EXISTING_RELATIONS)},
                             "fn": {r[0]: tuple(r[1:]) for r in _tl.conn.execute(_EXISTING_FUNCTIONS)},
                             "trg": {(r[0], r[1]): tuple(r[2:]) for r in _tl.conn.execute(_EXISTING_TRIGGERS)}}
            except Exception as exc:
                print(f"이미 있는 표 정의를 읽지 못했습니다(모두 실행): {type(exc).__name__}", flush=True)  # i18n-ignore: 로그
                found = {"rel": set(), "fn": {}, "trg": {}}
            self._be.existing[schema] = found
        return found

    def _make_unlogged(self, table: str):
        """예전에 보통 표로 만든 표를 UNLOGGED 로 바꾼다. 표 잠금(ACCESS EXCLUSIVE)을 짧게만 기다리고, 못 얻으면 다음 기동에
        다시 한다 — 다른 복제본이 그 표에 초당 수십 번 쓰는 동안 오래 기다리면 그 표의 읽기·쓰기가 모두 줄을 선다(외부 검토 N9)."""
        try:
            with self:
                self._begin()
                _tl.conn.execute(f"SET LOCAL lock_timeout = '{UNLOGGED_LOCK_TIMEOUT}'")
                row = _tl.conn.execute("SELECT relpersistence FROM pg_class WHERE oid = to_regclass(%s)", (table,)).fetchone()
                if row and row[0] == "p":
                    _tl.conn.execute(f"ALTER TABLE {table} SET UNLOGGED")
        except Exception as exc:
            print(f"{table} 표를 UNLOGGED 로 바꾸지 못했습니다(다음 기동에 다시): {type(exc).__name__}", flush=True)  # i18n-ignore: 로그

    def commit(self):
        """with 안에서 지금까지를 커밋한다. 다음 쓰기는 새 트랜잭션을 연다. 세이브포인트(안쪽 with) 안에서는 부르지 않는다."""
        if getattr(_tl, "conn", None) is not None and getattr(_tl, "outer", None) is not None and not _tl.txs:
            _tl.outer.__exit__(None, None, None)
            _tl.outer = None

    def close(self):
        pass


def session_connection():
    """풀 밖의 자동 커밋 연결 하나. 세션 advisory 잠금(리더·키 잠금)을 쥘 때 쓴다 — 트랜잭션을 열지 않으므로 잠금을 쥔 채
    다른 일을 기다려도 「트랜잭션 중 쉼」 한도에 걸리지 않고, 연결이 끊기면 PostgreSQL 이 잠금을 푼다(스펙 2026-10-24-002 R12).
    잠금은 다른 복제본이 쥔 동안 끝까지 기다려야 하므로 잠금·문장 한도를 끈다(외부 검토 1). 부른 쪽이 닫는다."""
    import psycopg
    conn = psycopg.connect(_backend().conninfo(5), autocommit=True)
    conn.execute("SET lock_timeout = 0")
    conn.execute("SET statement_timeout = 0")
    return conn


