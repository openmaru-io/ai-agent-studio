"""PostgreSQL 어댑터와 연결 풀. `store.connect()` 가 돌려주는 객체를 sqlite3 연결처럼 쓸 수 있게 한다.

호출하는 쪽은 `with store.connect() as conn: conn.execute("... ?", (값,))` 형태 그대로다.
- 같은 스레드가 이미 쥔 연결은 재사용한다. 안쪽 `with` 는 세이브포인트이고 가장 바깥 `with` 가 끝날 때만 커밋하고 풀에 돌려준다.
- `?` 는 `%s` 로 바꾼다(따옴표 안의 `?` 는 두고, 파라미터가 있으면 `%` 를 `%%` 로 쓴다).
- DDL(`CREATE ...`)은 프로세스마다 한 번만 실행한다. SQLite 표 정의를 PostgreSQL 로 옮겨 쓴다(`to_pg`).
SQLite 일 때는 이 모듈의 연결을 쓰지 않는다.
"""
